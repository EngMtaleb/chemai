"""Write chemai/api/stop_examples.py: the worked examples the /stop page loads.

  * two CCRO batches from the testbed record (doi:10.7481/1963162, CC BY 4.0), every 10 s:
    a long test batch whose best end lies inside it, and a short ESC batch that ended while
    its cost was still falling;
  * two slow cycles: an RO train between cleanings (deposit of Project 3) and a UF membrane
    between chemical cleans (Project 4), as daily live costs in the mid case of Parts D and C.

    python projects/p05_when_to_stop/make_stop_examples.py
"""
from pathlib import Path
import sys

import numpy as np
import pandas as pd

from chemai.config import CCROConfig
from chemai.data.nawi_ccro import read_dataset
from chemai.features.ccro_batches import COLUMNS, phase_of

HERE = Path(__file__).parent
OUT = HERE.parents[1] / "chemai" / "api" / "stop_examples.py"
sys.path.insert(0, str(HERE))


def batch(dataset: str, exp: str, seq: int, every_s: float = 10.0) -> dict:
    b = pd.read_parquet(HERE / "results" / "ccro_batches.parquet")
    row = b[(b.dataset == dataset) & (b.exp == exp) & (b.seq == seq)].iloc[0]
    df = read_dataset(dataset, columns=COLUMNS)
    g = df[(df.exp == exp) & (df.seq == seq)].sort_values("row")
    g = g[g.state.map(phase_of).isin(["startup", "stab", "filt"])]
    t = g.runtime_hr.to_numpy(float) * 3600
    t = t - t[0]
    keep = np.r_[0, np.flatnonzero(np.diff(np.floor(t / every_s)) > 0) + 1]
    g, t = g.iloc[keep], t[keep]
    return {
        "name": f"{'test batch' if dataset == 'dataset6' else 'development batch'}, {exp.split('/')[0]} no. {seq}",
        "t": [round(float(x), 1) for x in t],
        "power_kw": [round(float(x), 4) for x in g.feed_pump_power_draw_kw.to_numpy(float) + g.recirculation_pump_power_draw_kw.to_numpy(float)],
        "permeate_lpm": [round(float(x), 4) for x in g.permeate_flow_l_per_min.to_numpy(float)],
        "conductivity": [round(float(x), 3) for x in g.reject_conductivity_ms_per_cm.to_numpy(float)],
        "drain_kwh": round(float(row.drain_E_kwh if row.drain_min > 0 else CCROConfig().default_drain_kwh), 4),
        "brine_l": round(float(row.drain_Vrej_l if row.drain_min > 0 else CCROConfig().default_brine_l), 2),
    }


def ro_cycle(cycle_id: str = "B:482-524") -> dict:
    from step4_ro_cip_economics import MID, cycle_inputs
    from chemai.data.ro_deposit import load_daily
    from chemai.features.ro_physics import fouling_energy_penalty, specific_energy_per_bar
    c = next(x for x in cycle_inputs(load_daily()) if x["id"] == cycle_id)
    m = MID["price"] * fouling_energy_penalty(c["ndp"], c["d_dp"], MID["ndp0"], MID["dp0"], specific_energy_per_bar())
    return {"name": f"RO train {cycle_id.split(':')[0]}, cycle of {int(c['length'])} days (mid case: $0.10/kWh, NDP 20 bar)",
            "day": [float(x) for x in c["day"]], "live_cost": [round(float(x), 6) for x in m],
            "fixed_cost": MID["F"], "actual_days": c["length"]}


def uf_interval() -> dict:
    from step5_uf_economics import C_MID
    from chemai.features.uf_cycles import PSI_BAR
    daily = pd.read_parquet(HERE / "results" / "step5_uf_daily.parquet")
    a, b = pd.Timestamp("2014-03-18"), pd.Timestamp("2014-07-28")
    g = daily[(daily.index >= a) & (daily.index < b)]
    day = (g.index - a).days.to_numpy(float)
    start = g[(day >= 1) & (day <= 7)]
    lnr0, tmp0 = float(start.lnr.median()), float(start.tmp_psi.median()) * PSI_BAR
    keep = day >= 1
    m = C_MID["price"] / (36 * C_MID["eff"]) * np.clip(tmp0 * (np.exp(g.lnr.to_numpy(float)[keep] - lnr0) - 1), 0, None)
    return {"name": "UF membrane between two chemical cleans, 2014-03-18 to 2014-07-28 (mid case)",
            "day": [float(x) for x in day[keep]], "live_cost": [round(float(x), 7) for x in m],
            "fixed_cost": C_MID["F"], "actual_days": float((b - a).days)}


def main():
    examples = {
        "batch_long": batch("dataset6", "Exp1", 11),
        "batch_short": batch("dataset3", "Exp1", 40),
        "ro_cycle": ro_cycle(),
        "uf_interval": uf_interval(),
    }
    text = ('"""Worked examples for the /stop page - generated by '
            'projects/p05_when_to_stop/make_stop_examples.py, do not edit.\n\n'
            'CCRO batches: doi:10.7481/1963162 (CC BY 4.0). RO cycle: doi:10.5281/zenodo.21055948 (CC BY 4.0).\n'
            'UF interval: doi:10.5068/D1310B (CC0).\n"""\n\n'
            f"EXAMPLES = {examples!r}\n")
    OUT.write_text(text)
    print(OUT, round(OUT.stat().st_size / 1e3), "kB",
          {k: len(v.get("t", v.get("day"))) for k, v in examples.items()})


if __name__ == "__main__":
    main()
