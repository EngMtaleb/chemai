"""The what-if on waves (v9, note 5): published inputs + our phase-2C plant model -> wave_data.js (const WVDATA).

    python3 make_wave_data.py

Every number the five what-if pages show comes from here; nothing on them is typed by hand.

Published inputs (copied exactly from their sources):
  Mean wave power, kW per metre of wave crest
    northern Gulf, Iraqi coast, 19 m deep: 0.2664 (zero-crossing) and 0.386 (spectral, SWAN)
      Muttalib, Shareef & Hussein 2025, J. Environmental & Earth Sciences 7(1) 485-493, doi:10.30564/jees.v7i1.7146
    Oman, Table 2 (Pavg): Muscat 0.6, Masirah 9.07, Al Halaniyat 14.18 - Copernicus MFWAM, 2023-2025
      Al-Badi, AlHinai, Al Wahaibi & Al-Yahyai 2026, Energies 19, 2356, doi:10.3390/en19102356
  One device type: oscillating water column, typical width about 30 m, capture width ratio 15-40 % of the power
    passing its width (absorbed power) - prototype values, Babarit & Hals 2011 (EWTEC), Coastal Wiki Appendix B
Our model: the 12-train dispatch, October window (15-17 Oct 2023), the daylight + tank rule
  bigplant/big/energy/results/2023-10_nominal__daylight_tank_rule.json (the same 72-hour totals as results_summary.json)
"""
# In this repository the paths point at the project's own folders; the run used the working folders.

import hashlib
import json
import math
from pathlib import Path

HERE = Path(__file__).parent
RUN = HERE.parent / "research_package" / "bigplant" / "big" / "energy" / "results" / "2023-10_nominal__daylight_tank_rule.json"
run = json.loads(RUN.read_text())
m, tr = run["metrics"], run["trajectory"]
assert m["policy"] == "daylight_tank_rule" and len(tr) == 72

# the plant, from our model
E72 = m["total_electricity_kWh"]
E_day = E72 / 3
grid_share = m["grid_kWh"] / E72
grid_nosun = sum(t["grid_kWh"] for t in tr if t["PV_kW"] <= 1e-9) / m["grid_kWh"]
spare_hours = sum(1 for t in tr if t["PV_kW"] > t["load_kWh"] + 1e-9) / 3            # hours a day the sun beats the load
day = [{"h": t["hour"], "pv": round(t["PV_kW"], 1), "load": round(t["load_kWh"], 1), "grid": round(t["grid_kWh"], 1),
        "used": round(t["solar_used_kWh"], 1), "spare": round(t["solar_curtailed_kWh"], 1)} for t in tr[:24]]
for d in day:                                                                         # each hour balances
    assert abs(d["used"] + d["grid"] - d["load"]) < 0.5 and abs(d["used"] + d["spare"] - d["pv"]) < 0.5, d

# the seas and the device
SEAS = [
    {"k": "halaniyat", "sea": "Arabian Sea", "at": "Al Halaniyat", "lo": 14.18, "hi": 14.18, "src": "wv_oman"},
    {"k": "masirah", "sea": "Arabian Sea", "at": "Masirah", "lo": 9.07, "hi": 9.07, "src": "wv_oman"},
    {"k": "muscat", "sea": "Gulf of Oman", "at": "Muscat", "lo": 0.6, "hi": 0.6, "src": "wv_oman"},
    {"k": "gulf", "sea": "Northern Gulf", "at": "Iraqi coast, 19 m deep", "lo": 0.2664, "hi": 0.386, "src": "wv_gulf"},
]
B, CWR, N = 30.0, (0.15, 0.40), 10
for s in SEAS:
    s["one_kW"] = [s["lo"] * B * CWR[0], s["hi"] * B * CWR[1]]                   # one device, mean absorbed power
    s["ten_kWh_day"] = [N * v * 24 for v in s["one_kW"]]
    s["share_pct"] = [100 * v / E_day for v in s["ten_kWh_day"]]
    s["for10_devices"] = [math.ceil(0.10 * E_day / (v * 24)) for v in s["one_kW"][::-1]]
ratio = [9.07 / 0.386, 14.18 / 0.2664]                                              # Arabian Sea vs the northern Gulf

# the open-sea formula: P = rho g^2 H^2 T / (64 pi), in kW per metre
rho, g = 1025.0, 9.81
k = rho * g * g / (64 * math.pi) / 1000
examples = [{"H": 1, "T": 8, "P": k * 1 * 8}, {"H": 2, "T": 8, "P": k * 4 * 8}]

OUT = {
    "plant": {"E72_kWh": E72, "E_day_kWh": E_day, "grid_share_pct": 100 * grid_share, "sun_share_pct": m["PV_share_pct"],
              "grid_in_no_sun_hours_pct": 100 * grid_nosun, "spare_sun_hours_per_day": spare_hours,
              "date": tr[0]["time_kuwait"][:10], "policy": "daylight + tank rule",
              "file": "bigplant/big/energy/results/" + RUN.name, "sha256": hashlib.sha256(RUN.read_bytes()).hexdigest()},
    "day": day, "seas": SEAS, "B_m": B, "cwr": list(CWR), "N": N, "ratio": ratio,
    "formula_k": k, "examples": examples,
}
js = "/* generated by make_wave_data.py (v9, note 5) — the what-if on waves; do not edit by hand */\nconst WVDATA = " + json.dumps(OUT, ensure_ascii=False) + ";\n"
(HERE / "wave_data.js").write_text(js)

print(f"plant: {E72:,.0f} kWh per 72 h = {E_day:,.0f} kWh/day; grid {100 * grid_share:.1f} %, sun {m['PV_share_pct']:.1f} %;"
      f" grid in no-sun hours {100 * grid_nosun:.1f} %; sun beats the load {spare_hours:.0f} h a day")
for s in SEAS:
    print(f"{s['at']:24s} {s['lo']:.4g}-{s['hi']:.4g} kW/m | one device {s['one_kW'][0]:.2f}-{s['one_kW'][1]:.2f} kW |"
          f" ten: {s['ten_kWh_day'][0]:,.0f}-{s['ten_kWh_day'][1]:,.0f} kWh/day = {s['share_pct'][0]:.2f}-{s['share_pct'][1]:.2f} %"
          f" | devices for 10 %: {s['for10_devices'][0]}-{s['for10_devices'][1]}")
print(f"ratio {ratio[0]:.1f}-{ratio[1]:.1f}; k = {k:.4f}; examples {[round(e['P'], 2) for e in examples]}")
